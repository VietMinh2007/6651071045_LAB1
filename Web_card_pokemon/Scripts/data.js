// Khởi tạo LocalStorage cho Sản phẩm nếu chưa có
function initProductsStorage() {
  localStorage.setItem("pokecard_products", JSON.stringify(POKEMON_PRODUCTS));
}

// Lấy danh sách sản phẩm từ LocalStorage
function getProducts() {
  const data = localStorage.getItem("pokecard_products");
  if (!data) {
    initProductsStorage();
    return POKEMON_PRODUCTS;
  }
  try {
    const parsed = JSON.parse(data);
    if (!Array.isArray(parsed) || parsed.length !== 60 || !parsed[59] || parsed[59].name !== "Tinkaton ex Special Illustration Rare") {
      initProductsStorage();
      return POKEMON_PRODUCTS;
    }
    return parsed;
  } catch (e) {
    initProductsStorage();
    return POKEMON_PRODUCTS;
  }
}

// Lấy 1 sản phẩm theo ID
function getProductById(id) {
  const products = getProducts();
  const numId = parseInt(id, 10);
  return products.find(p => p.id === numId) || null;
}

// Format giá VNĐ
function formatVND(amount) {
  if (typeof amount !== "number" || isNaN(amount)) return "0đ";
  return amount.toLocaleString("vi-VN") + "đ";
}

